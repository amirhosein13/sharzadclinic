-- انتقال پیگیری‌های بازگردانیِ قدیمی از CUSTOM به نوع تازه‌ی خودشان.
--
-- مایگریشن جداست چون پستگرس اجازه نمی‌دهد مقدار تازه‌ی یک enum در همان
-- تراکنشی که اضافه شده، استفاده شود.
--
-- شرط‌ها محافظه‌کارانه‌اند تا یادداشت دستی منشی قربانی نشود: متنِ دلیل
-- ماشینی و دقیق است، و پیگیری بازگردانی هیچ‌وقت به نوبت وصل نیست.
UPDATE "follow_ups"
SET "kind" = 'WIN_BACK'
WHERE "kind" = 'CUSTOM'
  AND "appointmentId" IS NULL
  AND "reason" LIKE '%ماه است مراجعه نکرده%';
