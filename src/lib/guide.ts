/** فقط بخش‌هایی که این نقش واقعاً به آن‌ها دسترسی دارد */
export function guideFor(has: (permission: Permission) => boolean): GuideSection[] {
  return GUIDE.map((section) => ({
    ...section,
    cards: section.cards.filter((card) => !card.permission || has(card.permission)),
  })).filter((section) => section.cards.length > 0);
}
