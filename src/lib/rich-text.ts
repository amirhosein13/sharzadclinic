/**
 * ───────────────────────────────────────────────────────────────
 *  متن‌های بلند سایت (مقاله‌ی مجله و توضیح خدمات)
 * ───────────────────────────────────────────────────────────────
 *
 *  قالبی که <Prose> می‌فهمد عمداً کوچک است:
 *
 *      ## عنوان بزرگ
 *      ### عنوان کوچک
 *      - آیتم فهرست
 *      ۱. آیتم شماره‌دار
 *      **پررنگ**
 *      [متن پیوند](آدرس)
 *      خط خالی = پاراگراف تازه
 *
 *  ولی وقتی متن از یک هوش مصنوعی کپی می‌شود، پر است از چیزهایی که
 *  این قالب نمی‌فهمد: # تکی، *مورب*، __پررهنگ__، جدول، خط جداکننده،
 *  بلوک کد. اگر همان‌طور ذخیره شود، روی سایت به‌شکل ستاره و مربع خام
 *  دیده می‌شود — و کسی که متن را وارد کرده هیچ‌وقت نمی‌فهمد چرا.
 *
 *  tidyRichText همان متن را به زیرمجموعه‌ی پشتیبانی‌شده ترجمه می‌کند.
 */

/** خط جداکننده‌ی --- و *** و ___ که هوش مصنوعی بینِ بخش‌ها می‌گذارد */
const DIVIDER = /^\s*([-*_])\s*\1\s*\1[\s\-*_]*$/;

/** ```  و  ~~~  که دور بلوک کد می‌آید */
const FENCE = /^\s*(```|~~~)/;

/** | ستون | ستون | — جدول که Prose اصلاً نمی‌فهمد */
const TABLE_ROW = /^\s*\|.*\|\s*$/;
const TABLE_SEP = /^\s*\|[\s:|-]+\|\s*$/;

function tidyLine(line: string): string {
  let out = line.replace(/\r$/, "");

  // عنوان‌ها: # و #### و بیشتر، همه به ## و ### می‌خورند
  out = out.replace(/^\s{0,3}(#{1,6})\s+(.*)$/, (_m, hashes: string, text: string) =>
    (hashes.length <= 2 ? "## " : "### ") + text.trim().replace(/\s*#+\s*$/, ""),
  );

  // فهرست: * و + و • و – به - تبدیل می‌شوند
  out = out.replace(/^(\s*)[*+•–—]\s+/, "$1- ");

  // فهرست شماره‌دار با ) به نقطه
  out = out.replace(/^(\s*)(\d+)\)\s+/, "$1$2. ");

  // تورفتگی فهرست را صاف می‌کنیم؛ Prose فهرست تودرتو ندارد و اگر
  // خطی با فاصله شروع شود، اصلاً آیتم فهرست شناخته نمی‌شود
  out = out.replace(/^\s+(-\s)/, "$1").replace(/^\s+(\d+\.\s)/, "$1");

  return out;
}

function tidyInline(text: string): string {
  let out = text;

  // __پررنگ__ → **پررنگ**
  out = out.replace(/__([^_\n]+)__/g, "**$1**");

  // ~~خط‌خورده~~ → متن ساده
  out = out.replace(/~~([^~\n]+)~~/g, "$1");

  // `کد` → متن ساده
  out = out.replace(/`([^`\n]+)`/g, "$1");

  // ![توضیح](آدرس) → حذف؛ تصویر داخل متن پشتیبانی نمی‌شود و
  // آدرسش هم معمولاً به جایی بیرون از سایت اشاره می‌کند
  out = out.replace(/!\[[^\]]*\]\([^)]*\)/g, "");

  // *مورب* → **پررنگ**. شرطِ نبودن * در دو طرف لازم است تا **پررنگ**
  // که از قبل درست است، دوباره دستکاری نشود.
  out = out.replace(/(^|[^*])\*([^*\n]+)\*(?!\*)/g, "$1**$2**");

  return out;
}

/**
 * متن کپی‌شده از هر جایی را به قالبی که سایت می‌فهمد برمی‌گرداند.
 * ورودیِ از قبل درست، دست‌نخورده برمی‌گردد.
 */
export function tidyRichText(raw: string): string {
  if (!raw.trim()) return "";

  const lines = raw.replace(/\r\n/g, "\n").split("\n");
  const out: string[] = [];
  let inFence = false;

  for (const line of lines) {
    if (FENCE.test(line)) {
      inFence = !inFence;
      continue; // خودِ ``` هیچ‌وقت نباید در متن بماند
    }
    if (inFence) {
      out.push(line);
      continue;
    }
    if (DIVIDER.test(line)) continue;
    if (TABLE_SEP.test(line)) continue;

    // جدول را به فهرست تبدیل می‌کنیم تا محتوایش گم نشود
    if (TABLE_ROW.test(line)) {
      const cells = line
        .trim()
        .replace(/^\||\|$/g, "")
        .split("|")
        .map((c) => tidyInline(c.trim()))
        .filter(Boolean);
      if (cells.length) out.push(`- ${cells.join(" — ")}`);
      continue;
    }

    out.push(tidyInline(tidyLine(line)));
  }

  return (
    out
      .join("\n")
      // بیش از یک خط خالی پشت‌سرهم بی‌فایده است
      .replace(/\n{3,}/g, "\n\n")
      // فاصله‌ی انتهای خط‌ها
      .replace(/[ \t]+$/gm, "")
      .trim()
  );
}

/**
 * پرامپتی که مدیر کلینیک آن را کپی می‌کند، در هر دستیار هوش مصنوعی
 * می‌گذارد، و خروجی‌اش مستقیماً در ویرایشگر قابل چسباندن است.
 *
 * مهم‌ترین بخشش همان فهرست «فقط این علامت‌ها» است: بدون آن، خروجی پر
 * از جدول و ایموجی و # تکی می‌شود.
 */
export function articlePrompt(topic = "موضوع مقاله را اینجا بنویس") {
  return `تو نویسنده‌ی مجله‌ی یک کلینیک زیبایی و پوست در ایران هستی.

موضوع: ${topic}

یک مقاله‌ی فارسی بنویس با این ویژگی‌ها:

لحن و محتوا
- ساده، گرم و محترمانه؛ طوری که یک مراجعه‌کننده‌ی معمولی راحت بخواند
- بین ۶۰۰ تا ۹۰۰ کلمه
- کاربردی و صادقانه: اگر چیزی محدودیت یا عارضه دارد، بگو
- هیچ وعده‌ی قطعی نده («صددرصد»، «برای همیشه»، «تضمینی» ممنوع)
- ادعای درمانی نکن و دارو تجویز نکن؛ جایی که لازم است بنویس با پزشک مشورت شود
- آمار و عدد از خودت نساز
- اسم برند تجاری نیاور
- در پایان یک بند کوتاه دعوت به مشاوره بنویس، بدون اغراق تبلیغاتی

قالب متن — فقط و فقط از این علامت‌ها استفاده کن:
- «## » برای عنوان بخش
- «### » برای عنوان فرعی
- «- » برای فهرست
- «۱. » برای فهرست شماره‌دار
- «**متن**» برای پررنگ‌کردن
- بین پاراگراف‌ها یک خط خالی

این‌ها را به‌هیچ‌وجه استفاده نکن: جدول، ایموجی، عنوان با یک # تنها،
*مورب*، ~~خط‌خورده~~، بلوک کد، خط جداکننده‌ی ---، لینک و تصویر.

خروجی را دقیقاً در این سه بخش بده:

عنوان:
(یک خط، حداکثر ۷۰ کاراکتر، بدون علامت)

خلاصه:
(یک جمله، حداکثر ۱۶۰ کاراکتر — همان چیزی که در گوگل دیده می‌شود)

متن:
(خودِ مقاله)`;
}
